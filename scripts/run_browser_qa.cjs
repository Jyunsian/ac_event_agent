const {chromium}=require('playwright');
const fs=require('node:fs');
const path=require('node:path');
const assert=require('node:assert/strict');
(async()=>{
  const [url,configPath,output]=process.argv.slice(2);
  const {runId,failedId,legacyId}=JSON.parse(fs.readFileSync(configPath));fs.mkdirSync(output);
  const browser=await chromium.launch({headless:true,channel:process.env.PLAYWRIGHT_CHANNEL||'chrome'});
  try {
    let page=await browser.newPage({viewport:{width:1440,height:900}});
    await page.goto(`${url}/workspace?run=${runId}`);
    await page.getByText('等待開始分析',{exact:true}).waitFor();
    assert.equal(await page.getByRole('link',{name:'開啟分析工作區',exact:true}).count(),0);
    assert.equal(await page.getByRole('heading',{name:'分析助理',level:1,exact:true}).count(),0);
    assert.equal(await page.locator('progress').count(),0);
    await page.screenshot({path:path.join(output,'queued.png')});
    await page.close(); // Original caller is really gone before Worker begins.
    fs.writeFileSync(path.join(output,'caller-closed'),'synthetic test coordination',{flag:'wx'});
    page=await browser.newPage({viewport:{width:1440,height:900}});
    const errors=[];page.on('pageerror',e=>errors.push(String(e)));
    await page.goto(`${url}/runs/${runId}`);
    await page.getByRole('link',{name:'開啟分析工作區',exact:true}).waitFor({timeout:60000});
    await page.reload();
    await page.getByText('基礎報告已發布',{exact:true}).waitFor();
    await page.screenshot({path:path.join(output,'ready.png')});
    const view=await (await page.request.get(`${url}/api/runs/${runId}/view`)).json();
    assert(view.ready && view.report_version===1);
    assert(view.progress.completed_stages.includes('report'));
    await page.getByRole('link',{name:'開啟分析工作區',exact:true}).click();
    await page.getByRole('heading',{name:'分析助理',level:1,exact:true}).waitFor();
    await page.getByRole('heading',{name:/目前還不能選出值得優先測試的事件|找到有歷史資料支持的事件條件/}).waitFor();
    await require('./accessibility_qa.cjs')(page,output);
    assert.equal(await page.getByRole('button',{name:'送出',exact:true}).isDisabled(),true);
    const download=await page.request.get(`${url}/api/runs/${runId}/reports/1/json`);
    assert.equal(download.status(),200);const report=await download.json();assert.equal(report.run_id,runId);
    const reportUrl=`**/api/runs/${runId}/reports/1/json`;
    await page.getByRole('tab',{name:'候選事件',exact:true}).click();
    const candidateRows=page.locator('[data-candidate-id]');
    assert.equal(await candidateRows.count(),report.candidates.length);
    const originalIds=report.candidates.map(c=>c.candidate_id);
    assert.deepEqual(await candidateRows.evaluateAll(rows=>rows.map(r=>r.dataset.candidateId)),originalIds);
    await page.getByRole('combobox').selectOption('coverage');
    const expected=report.candidates.slice().sort((a,b)=>{
      const av=a.metrics?.coverage,bv=b.metrics?.coverage;
      return av==null?(bv==null?a.candidate_id.localeCompare(b.candidate_id):1):bv==null?-1:bv-av||a.candidate_id.localeCompare(b.candidate_id);
    }).map(c=>c.candidate_id);
    assert.deepEqual(await candidateRows.evaluateAll(rows=>rows.map(r=>r.dataset.candidateId)),expected);
    await page.getByRole('combobox').selectOption('original');
    assert.deepEqual(await candidateRows.evaluateAll(rows=>rows.map(r=>r.dataset.candidateId)),originalIds);
    if(report.candidates.length){
      await candidateRows.first().getByRole('button').click();
      const detail=page.getByRole('region',{name:'完整候選證據',exact:true});
      await detail.waitFor();
      const evidence=JSON.parse(await detail.locator('details').filter({has:page.getByText('給工程師的事件定義與來源',{exact:true})}).locator('pre').textContent());
      assert.deepEqual(evidence.event_spec,report.candidates[0].event_spec);
      assert.deepEqual(evidence.validation.metrics,report.candidates[0].metrics);
    }
    await page.screenshot({path:path.join(output,'report-candidates.png')});
    await page.route(reportUrl,route=>route.fulfill({status:503,body:'negative test: unavailable'}));
    await page.getByRole('button',{name:'重新讀取報告'}).click();
    await page.getByRole('alert').filter({hasText:'REPORT_READ_FAILED_503'}).waitFor();
    assert.deepEqual(await candidateRows.evaluateAll(rows=>rows.map(r=>r.dataset.candidateId)),originalIds);
    await page.unroute(reportUrl);
    const changed=JSON.stringify({...report,title:'negative test: same version changed'});
    const changedHash=require('node:crypto').createHash('sha256').update(changed).digest('hex');
    await page.route(reportUrl,route=>route.fulfill({status:200,contentType:'application/json',headers:{etag:`"${changedHash}"`},body:changed}));
    await page.getByRole('button',{name:'重新讀取報告'}).click();
    await page.getByRole('alert').filter({hasText:'REPORT_VERSION_CHANGED'}).waitFor();
    assert.deepEqual(await candidateRows.evaluateAll(rows=>rows.map(r=>r.dataset.candidateId)),originalIds);
    await page.unroute(reportUrl);
    // A valid checksum does not authorize content from another run.
    const wrong=JSON.stringify({...report,run_id:legacyId});
    const wrongHash=require('node:crypto').createHash('sha256').update(wrong).digest('hex');
    await page.route(reportUrl,route=>route.fulfill({status:200,contentType:'application/json',headers:{etag:`"${wrongHash}"`},body:wrong}));
    await page.getByRole('button',{name:'重新讀取報告'}).click();
    await page.getByRole('alert').filter({hasText:'REPORT_IDENTITY_MISMATCH'}).waitFor();
    assert.deepEqual(await candidateRows.evaluateAll(rows=>rows.map(r=>r.dataset.candidateId)),originalIds);
    await page.unroute(reportUrl);
    await page.getByRole('button',{name:'重新讀取報告'}).click();
    await page.getByRole('button',{name:'重新讀取報告'}).waitFor();
    await page.getByRole('tab',{name:'資料品質',exact:true}).click();
    await page.getByRole('heading',{name:'這份資料是否足夠完整？'}).waitFor();
    assert.equal(await page.locator('.facts div').filter({hasText:'沒有行為紀錄的用戶'}).locator('[data-value]').getAttribute('data-value'),String(report.summary.quality.zero_event_users));
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.screenshot({path:path.join(output,'report-quality-mobile.png')});
    await page.setViewportSize({width:1440,height:900});
    await page.getByRole('tab',{name:'圖表',exact:true}).click();
    await page.getByRole('heading',{name:'不同條件選中的是同一批人嗎？',exact:true}).waitFor();
    assert.equal(await page.getByRole('alert').count(),0);
    assert.equal(await page.locator('.chart-section svg').count()>0,true);
    const tableRows=async section=>section.locator('tbody tr').evaluateAll(rows=>rows.map(row=>[row.dataset.candidateId,...[...row.querySelectorAll('td')].slice(1).map(td=>td.getAttribute('data-value')??'未知')]));
    const cell=v=>v===null?'未知':String(v);
    const scatterSection=page.locator('[data-chart-type="scatter"]');
    assert.equal(await scatterSection.getAttribute('data-sample-size'),String(report.candidates.find(c=>c.metrics)?.metrics.groups.all.users));
    assert.deepEqual(await tableRows(scatterSection),report.candidates.filter(c=>c.metrics).map(c=>[c.candidate_id,cell(c.metrics.coverage),cell(c.metrics.groups.triggered.arpu_usd)]));
    const lineSections=page.locator('[data-chart-type="line"]');
    const families=new Map();
    for(const p of report.diagnostics.sensitivity.points){if(!p.family)continue;const f=p.family;const key=JSON.stringify([f.op,f.ad_format,f.window_hours]);families.set(key,[...(families.get(key)||[]),p]);}
    assert.equal(await lineSections.count(),families.size);
    let li=0;
    for(const [family,points] of families){const [op]=JSON.parse(family);const section=lineSections.nth(li++);assert.equal(await section.getAttribute('data-sample-size'),String(report.diagnostics.sensitivity.cohort_users));
      assert.deepEqual(await tableRows(section),points.slice().sort((a,b)=>a.threshold-b.threshold).map(p=>[p.candidate_id,cell(op==='engaged_seconds'?p.threshold/3600:p.threshold),cell(p.coverage)]));
    }
    const heatSection=page.locator('[data-chart-type="heatmap"]');const heatIds=report.diagnostics.overlap.comparison_ids;
    const heatRows=[];for(const p of report.diagnostics.overlap.pairs){const a=String(heatIds.indexOf(p.a)),b=String(heatIds.indexOf(p.b));heatRows.push([p.a,a,b,cell(p.jaccard)]);if(p.a!==p.b)heatRows.push([p.b,b,a,cell(p.jaccard)]);}
    assert.deepEqual(await tableRows(heatSection),heatRows);
    assert.equal(await heatSection.getAttribute('data-sample-size'),String(report.diagnostics.overlap.cohort_users));
    await page.screenshot({path:path.join(output,'report-charts.png')});
    await heatSection.scrollIntoViewIfNeeded();
    await page.screenshot({path:path.join(output,'report-heatmap.png')});
    await page.setViewportSize({width:390,height:844});
    await heatSection.scrollIntoViewIfNeeded();
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.screenshot({path:path.join(output,'report-heatmap-mobile.png')});
    await page.setViewportSize({width:1440,height:900});
    await page.goto(`${url}/history`);
    await page.locator(`a[href="/runs/${runId}"]`).waitFor();await page.reload();
    await page.locator(`a[href="/runs/${runId}"]`).waitFor();
    await page.screenshot({path:path.join(output,'history.png')});
    await page.goto(`${url}/runs/${failedId}`);
    await page.getByRole('alert').filter({hasText:'這次分析超過可用的處理時間'}).waitFor();
    await page.screenshot({path:path.join(output,'a11y-failed-run.png')});
    await page.getByRole('button',{name:'重新嘗試分析',exact:true}).click();
    await page.getByText('等待開始分析',{exact:true}).waitFor();
    await page.goto(`${url}/workspace?run=${legacyId}`);
    await page.getByRole('alert').filter({hasText:'報告尚未準備好'}).waitFor();
    assert.equal(await page.getByRole('heading',{name:'分析助理',level:1,exact:true}).count(),0);
    assert.equal(await page.getByRole('button',{name:'重新嘗試分析',exact:true}).count(),0);
    await page.setViewportSize({width:390,height:844});
    assert.equal(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth),false);
    await page.screenshot({path:path.join(output,'unpublished-mobile.png')});
    assert.equal(errors.length,0,errors.join('\n'));
    fs.writeFileSync(path.join(output,'checks.json'),JSON.stringify({runId,failedId,legacyId,ready:view.ready,
      stages:view.progress.completed_stages,errors,checks:['caller closed','same run reopened','ready gates workspace','download identity','candidate sort restored','exact event spec','null not zero','failed refresh retains report','wrong identity rejected','quality artifact value','history reload','explicit technical retry','unpublished success rejected','no fake percentage']},null,2),{flag:'wx'});
    console.log(JSON.stringify({ready:view.ready,errors}));
    await require('./chart_fixture_qa.cjs')(url,output);
  } finally {await browser.close();}
})().catch(e=>{console.error(e);process.exitCode=1;});
