const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const fs=require('node:fs');
const [base,runId,directory,mode]=process.argv.slice(2);
(async()=>{
 fs.mkdirSync(directory,{recursive:true});
 const browser=await chromium.launch({channel:'chrome',headless:true});
 try{
  const page=await browser.newPage({viewport:{width:1440,height:900}});
  await require('./message_fixture_qa.cjs')(browser,base,directory);
  await page.goto(`${base}/workspace?run=${runId}`);
  await page.getByRole('heading',{name:'高收益玩家更常做了什麼？',exact:true}).waitFor();
  if(mode==='no-key'){
    await page.getByText('分析助理目前尚未啟用，暫時無法回覆問題。 報告仍可正常查看。',{exact:true}).waitFor();
    assert.equal(await page.getByLabel('詢問分析助理').count(),0);
    assert.equal(await page.getByRole('button',{name:'送出',exact:true}).count(),0);
    await page.screenshot({path:`${directory}/chat-no-key.png`});
    console.log(JSON.stringify({actualNodeWithoutKey:true,sendDisabled:true,reportVisible:true}));return;
  }
  await page.getByRole('tab',{name:'候選事件',exact:true}).click();
  await page.getByRole('region',{name:'優先候選完整比較',exact:true}).getByRole('button').first().click();
  const candidate=await page.locator('[data-candidate-id]').first().getAttribute('data-candidate-id');
  assert((await page.locator('.composer .context-chip').textContent()).includes('已選事件'));
  const input=page.getByLabel('詢問分析助理');
  await input.fill('中文輸入');
  await input.dispatchEvent('compositionstart');await input.press('Enter');
  assert.equal(await page.locator('.chat-message').count(),0);
  await input.dispatchEvent('compositionend');await input.press('Shift+Enter');
  assert((await input.inputValue()).includes('\n'));
  await input.fill('[long] 請解釋目前候選');
  await page.getByRole('button',{name:'送出',exact:true}).click();
  await page.locator('.chat-message').filter({has:page.getByRole('heading',{name:'分析助理',exact:true})}).waitFor();
  const selectedContext=await page.locator('.chat-message-user').first().locator('.message-context').textContent();
  assert(selectedContext.includes('已選事件'));
  await page.locator('.tool-activity summary').filter({hasText:'已完成'}).first().waitFor();
  const cid=new URL(page.url()).searchParams.get('conversation');assert(cid);
  const before=await page.locator('.chat-message').count();
  await page.locator('.chat-scroll').evaluate(el=>{el.scrollTop=0;el.dispatchEvent(new Event('scroll'));});
  await input.fill('請再次解讀');await input.press('Enter');
  await page.getByRole('button',{name:'有新訊息，移至底部'}).waitFor();
  assert((await page.locator('.chat-scroll').evaluate(el=>el.scrollTop))<50);
  await page.getByRole('button',{name:'有新訊息，移至底部'}).click();
  await page.waitForFunction(n=>document.querySelectorAll('.chat-message').length>=n,before+2);
  await page.locator('.reference-button').last().click();
  await page.waitForURL(url=>url.searchParams.has('artifact'));
  await page.getByRole('region',{name:'完整候選證據',exact:true}).waitFor();
  assert(new URL(page.url()).searchParams.get('artifact'));
  await page.reload();await page.locator('.chat-message').first().waitFor();
  assert.equal(new URL(page.url()).searchParams.get('conversation'),cid);
  assert((await page.locator('.composer .context-chip').textContent()).includes('已選事件'));
  await input.fill('[fail] 測試失敗');await input.press('Enter');
  await page.getByText('回覆失敗 · 助理暫時無法完成回覆，請稍後再試。',{exact:true}).waitFor();
  await page.getByRole('button',{name:'重試原問題'}).last().click();
  await page.waitForFunction(()=>[...document.querySelectorAll('.chat-message')].filter(el=>el.textContent.includes('[fail]')).length===2);
  await page.locator('.chat-message').filter({hasText:'[fail] 測試失敗'}).last().locator('.tool-activity summary').filter({hasText:'已完成'}).waitFor();
  await input.fill('[slow] 測試取消');await input.press('Enter');
  const pending=page.locator('.chat-message').filter({hasText:'[slow] 測試取消'});
  await pending.getByText('分析助理處理中',{exact:true}).waitFor();
  await input.fill('[queued] 測試排隊');await input.press('Enter');
  const queued=page.locator('.chat-message').filter({hasText:'[queued] 測試排隊'});
  await queued.getByText('排隊中',{exact:true}).waitFor();
  await queued.getByRole('button',{name:'取消',exact:true}).click();await queued.getByText('已取消',{exact:true}).waitFor();
  await pending.getByRole('button',{name:'取消',exact:true}).click();await pending.getByText('已取消',{exact:true}).waitFor();
  await page.screenshot({path:`${directory}/chat-desktop.png`});
  await page.setViewportSize({width:390,height:844});
  await page.getByRole('button',{name:'對話',exact:true}).click();
  assert((await page.evaluate(()=>document.documentElement.scrollWidth))<=390);
  await page.screenshot({path:`${directory}/chat-mobile.png`});
  console.log(JSON.stringify({synthetic:true,conversation:cid,selectedCandidate:candidate,ime:true,refresh:true,cancel:true,retry:true,reference:true,noForcedScroll:true}));
 }finally{await browser.close();}
})().catch(error=>{console.error(error);process.exitCode=1;});
